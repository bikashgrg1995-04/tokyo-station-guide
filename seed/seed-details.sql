SELECT l.id, s.id, ROW_NUMBER() OVER (PARTITION BY l.id ORDER BY s.name), NULL
FROM m
JOIN stations s ON s.slug = m.station
JOIN lines l ON l.slug = m.line
WHERE NOT EXISTS (
  SELECT 1 FROM line_stations x WHERE x.line_id = l.id AND x.station_id = s.id
);

