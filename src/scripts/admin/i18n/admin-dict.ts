export function translate(text: string): string | null {
  const core = text.replace(/\s+/g, " ").trim();
  if (!core) return null;
  const hit = exact[core];
  if (hit !== undefined) return hit;
  for (const [re, fn] of patterns) {
    const m = core.match(re);
    if (m) return fn(m);
  }
  return null;
}
